@dataclass
class EncounterMetadata:
    encounter_id: str
    patient_id: str
    encounter_date: str
    department: str
    encounter_type: str
    age_years: int
    sex: str
    synthetic_name: str


@dataclass
class PipelineRunResult:
    encounter_id: str
    metadata: EncounterMetadata
    all_findings: List[Finding]
    confirmed_findings: List[Finding]
    hypotheses: List[Hypothesis]
    claims: List[Claim]
    verdicts: List[Verdict]
    scored: List[ScoreResult]
    unscored: List[Hypothesis]
    event_store: EventStore
    final_view: CaseView
    total_events: int


def load_available_encounters(sample_dir: str = "sample_data") -> List[EncounterMetadata]:
    """Read encounter and patient metadata from sample CSV files."""
    patients_file = os.path.join(sample_dir, "patients.csv")
    encounters_file = os.path.join(sample_dir, "encounters.csv")

    patients_map: Dict[str, Dict[str, str]] = {}
    if os.path.exists(patients_file):
        with open(patients_file, "r", encoding="utf-8") as f:
            for row in csv.DictReader(f):
                patients_map[row["patient_id"]] = row

    encounters: List[EncounterMetadata] = []
    if os.path.exists(encounters_file):
        with open(encounters_file, "r", encoding="utf-8") as f:
            for row in csv.DictReader(f):
                p_id = row["patient_id"]
                p_info = patients_map.get(p_id, {})
                try:
                    age = int(p_info.get("age_years", 0))
                except (ValueError, TypeError):
                    age = 0
                encounters.append(
                    EncounterMetadata(
                        encounter_id=row["encounter_id"],
                        patient_id=p_id,
                        encounter_date=row.get("encounter_date", ""),
                        department=row.get("department", "general"),
                        encounter_type=row.get("encounter_type", "outpatient"),
                        age_years=age,
                        sex=p_info.get("sex", "unknown"),
                        synthetic_name=p_info.get("synthetic_name", f"Synthetic Patient {p_id}"),
                    )
                )
    return encounters


def run_pipeline_for_encounter(
    encounter_id: str,
    sample_dir: str = "sample_data",
) -> PipelineRunResult:
    """Execute the complete Medagents Stages 1–5 pipeline for a chosen synthetic encounter.

    Follows the deterministic execution flow in scripts/run_demo.py:
    1. Extract findings from sample_data.
    2. Populate append-only EventStore via scoped GraphClient (stored as T6).
    3. Simulate clinician checkpoint 1 confirmation (remains T6, synthetic provenance preserved).
    4. Propose candidate hypotheses and evidence claims.
    5. Verify claims through deterministic verifiers.
    6. Run deterministic Bayesian scoring engine.
    """
    encounters = load_available_encounters(sample_dir)
    metadata = next((e for e in encounters if e.encounter_id == encounter_id), None)
    if not metadata:
        metadata = EncounterMetadata(
            encounter_id=encounter_id,
            patient_id="PT-UNKNOWN",
            encounter_date="2026-04-08",
            department="general_medicine",
            encounter_type="outpatient",
            age_years=35,
            sex="other_or_not_recorded",
            synthetic_name="Synthetic Demonstration Patient",
        )

    # Deterministic clock and id factory
    clock = FixedClock("2026-04-08T10:00:00+00:00")
    id_factory = DeterministicIdFactory()
    event_store = EventStore()
    kb = KB.create_default()

    # Add custom fever/myalgia LRs to KB to demonstrate rich multi-finding reasoning
    custom_lrs = [
        LREntry(
            id="lr-dengue-myalgia",
            disease=ClinicalCode(system="SNOMED-CT", code="38362002", display="Dengue fever"),
            finding=ClinicalCode(system="SNOMED-CT", code="68962001", display="Myalgia (finding)"),
            lr_positive=1.6,
            lr_negative=0.8,
            population="adult acute fever",
            source=LREntrySource(type=LRSourceType.STUDY, citation="Synthetic Demonstration LR"),
            quality=LRQuality.MODERATE,
            reviewed_by=["reviewer-demo-01", "reviewer-demo-02"],
            version="kb-0.1.0",
        ),
        LREntry(
            id="lr-malaria-fever",
            disease=ClinicalCode(system="SNOMED-CT", code="85940003", display="Malaria"),
            finding=ClinicalCode(system="SNOMED-CT", code="386661006", display="Fever (finding)"),
            lr_positive=1.4,
            lr_negative=0.2,
            population="adult acute fever",
            source=LREntrySource(type=LRSourceType.STUDY, citation="Synthetic Demonstration LR"),
            quality=LRQuality.MODERATE,
            reviewed_by=["reviewer-demo-01", "reviewer-demo-02"],
            version="kb-0.1.0",
        ),
    ]
    demo_kb = kb.model_copy(update={"lr_entries": kb.lr_entries + custom_lrs})

    # Step 1: Extraction
    extraction_result = extract_all_findings(sample_dir)
    enc_findings = [f for f in extraction_result.findings if f.encounter_id == encounter_id]

    # Step 2: Ingestion client
    ingest_client = GraphClient(
        component="ingestion",
        component_version="0.1.0",
        encounter_id=encounter_id,
        db=event_store,
        clock=clock,
        id_factory=id_factory,
    )
    p_context = PatientContext(
        patient_id=metadata.patient_id,
        age=metadata.age_years,
        sex=metadata.sex,
        region="south_india",
        month="04",
    )
    ingest_client.set_context(p_context)

    for f in enc_findings:
        ingest_client.add_finding(f)

    # Step 3: Clinician Checkpoint 1 (Review & Confirmation)
    clinician_client = GraphClient(
        component="checkpoint_1",
        component_version="1.0.0",
        encounter_id=encounter_id,
        db=event_store,
        clock=clock,
        id_factory=id_factory,
    )
    # Confirm up to 3 present findings for demonstration
    present_findings = [f for f in enc_findings if f.assertion == Assertion.PRESENT]
    confirmed_findings_list: List[Finding] = []
    for f in present_findings[:3]:
        confirmed_f = clinician_client.confirm_finding(
            finding_id=f.id,
            by="Dr. A. Rao, MD (Simulated Reviewer)",
        )
        confirmed_findings_list.append(confirmed_f)

    # Step 4: Propose Hypotheses & Claims
    kb_client = GraphClient(
        component="kb_lookup",
        component_version="0.1.0",
        encounter_id=encounter_id,
        db=event_store,
        clock=clock,
        id_factory=id_factory,
    )
    prop_client = GraphClient(
        component="proposer",
        component_version="0.1.0",
        encounter_id=encounter_id,
        db=event_store,
        clock=clock,
        id_factory=id_factory,
    )

    h_dengue = Hypothesis(
        id="h-dengue",
        encounter_id=encounter_id,
        name="Dengue fever",
        origin=[HypothesisOrigin.KB],
        must_not_miss=True,
        prior=demo_kb.priors_table.get("Dengue fever", 0.20),
        status=HypothesisStatus.ACTIVE,
        round=1,
    )
    h_malaria = Hypothesis(
        id="h-malaria",
        encounter_id=encounter_id,
        name="Malaria",
        origin=[HypothesisOrigin.KB, HypothesisOrigin.MNM],
        must_not_miss=True,
        prior=demo_kb.priors_table.get("Malaria", 0.08),
        status=HypothesisStatus.ACTIVE,
        round=1,
    )
    h_sepsis = Hypothesis(
        id="h-sepsis",
        encounter_id=encounter_id,
        name="Bacterial sepsis",
        origin=[HypothesisOrigin.MNM],
        must_not_miss=True,
        prior=demo_kb.priors_table.get("Bacterial sepsis", 0.02),
        status=HypothesisStatus.ACTIVE,
        round=1,
    )
    h_rare = Hypothesis(
        id="h-rare-arbovirus",
        encounter_id=encounter_id,
        name="Rare Arbovirus Variant",
        origin=[HypothesisOrigin.LLM],
        must_not_miss=False,
        prior=None,
        status=HypothesisStatus.ACTIVE,
        round=1,
    )

    for h in [h_dengue, h_malaria, h_sepsis]:
        kb_client.add_hypothesis(h)
    prop_client.add_hypothesis(h_rare)

    hypotheses_list = [h_dengue, h_malaria, h_sepsis, h_rare]

    # Propose evidence claims linking confirmed findings
    claims_list: List[Claim] = []
    claim_idx = 1
    for f in confirmed_findings_list:
        display_lower = f.code.display.lower()
        if "fever" in display_lower:
            c_dengue = Claim(
                claim_id=f"c-{claim_idx:02d}",
                encounter_id=encounter_id,
                type=ClaimType.FINDING_DISEASE_LINK,
                finding_id=f.id,
                hypothesis_id=h_dengue.id,
                proposed_relation="supports",
                proposed_by="clinical-proposer",
                round=1,
            )
            claims_list.append(c_dengue)
            prop_client.add_claim(c_dengue)
            claim_idx += 1

            c_malaria = Claim(
                claim_id=f"c-{claim_idx:02d}",
                encounter_id=encounter_id,
                type=ClaimType.FINDING_DISEASE_LINK,
                finding_id=f.id,
                hypothesis_id=h_malaria.id,
                proposed_relation="supports",
                proposed_by="clinical-proposer",
                round=1,
            )
            claims_list.append(c_malaria)
            prop_client.add_claim(c_malaria)
            claim_idx += 1
        elif "myalgia" in display_lower:
            c_myalgia = Claim(
                claim_id=f"c-{claim_idx:02d}",
                encounter_id=encounter_id,
                type=ClaimType.FINDING_DISEASE_LINK,
                finding_id=f.id,
                hypothesis_id=h_dengue.id,
                proposed_relation="supports",
                proposed_by="clinical-proposer",
                round=1,
            )
            claims_list.append(c_myalgia)
            prop_client.add_claim(c_myalgia)
            claim_idx += 1

    # Add Must-Not-Miss claim
    c_mnm = Claim(
        claim_id=f"c-{claim_idx:02d}",
        encounter_id=encounter_id,
        type=ClaimType.MNM_STATUS,
        hypothesis_id=h_sepsis.id,
        proposed_by="mnm-rule-proposer",
        round=1,
    )
    claims_list.append(c_mnm)
    prop_client.add_claim(c_mnm)

    # Step 5: Verification Layer
    verifiers = [
        KBLinkChecker(),
        LabInterpreterVerifier(),
        MNMChecker(),
        ConsistencyChecker(),
    ]
    view_current = prop_client.view()
    verif_client = GraphClient(
        component="verifier",
        component_version="0.1.0",
        encounter_id=encounter_id,
        db=event_store,
        clock=clock,
        id_factory=id_factory,
    )
    verdicts = dispatch(claims_list, verifiers, view_current, demo_kb)
    for v in verdicts:
        verif_client.add_verdict(v)

    # Step 6: Bayesian Scoring Engine
    view_final = verif_client.view()
    scored, unscored = score_all_hypotheses(view_final, demo_kb)

    total_events = event_store.get_current_version(encounter_id)

    return PipelineRunResult(
        encounter_id=encounter_id,
        metadata=metadata,
        all_findings=enc_findings,
        confirmed_findings=confirmed_findings_list,
        hypotheses=hypotheses_list,
        claims=claims_list,
        verdicts=verdicts,
        scored=scored,
        unscored=unscored,
        event_store=event_store,
        final_view=view_final,
        total_events=total_events,
    )
