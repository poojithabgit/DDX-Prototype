"""
src/ui/engine.py

Backend integration service for Medagents Clinical Decision Support Dashboard.
Connects Streamlit UI cleanly to existing Stage 1–5 modules without altering core logic.

Strict Safety Invariants:
- All data in sample_data/ is synthetic.
- Machine-extracted findings from synthetic datasets remain TrustTier.T6.
- Findings with synthetic provenance are strictly excluded from Bayesian updates (LR = 1.0).
- Probabilities are calculated deterministically via Bayes' theorem in odds space (src.reasoning.scorer),
  NEVER estimated or generated by the UI frontend.
- Must-Not-Miss conditions are preserved independently regardless of score rank.
"""

